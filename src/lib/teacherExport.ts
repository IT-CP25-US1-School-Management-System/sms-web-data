export function getThaiColumnLabel(rawHeader: unknown): string {
  const header = String(rawHeader ?? '')
    .replace(/^\uFEFF/, '')
    .trim()
  const normalizedHeader = header.toLowerCase()

  if (normalizedHeader === 'id' || normalizedHeader.endsWith('_id')) return header

  const exactLabel = THAI_COLUMN_LABELS[normalizedHeader]
  if (exactLabel) return exactLabel

  const matchedPrefix = COLUMN_PREFIXES.find(({ value }) => normalizedHeader.startsWith(value))
  const fieldName = matchedPrefix
    ? normalizedHeader.slice(matchedPrefix.value.length)
    : normalizedHeader
  const fieldLabel = THAI_COLUMN_LABELS[fieldName]
  const translatedLabel =
    fieldLabel ||
    fieldName
      .split(/[_\s-]+/)
      .map((word) => THAI_WORDS[word] || word)
      .join(' ')

  return matchedPrefix?.label ? `${matchedPrefix.label}: ${translatedLabel}` : translatedLabel
}
